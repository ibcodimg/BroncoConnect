import { randomBytes } from 'node:crypto';
import { Schema, model, type InferSchemaType } from 'mongoose';
import { DAYS, LOOKING_FOR } from '../../../shared/types';

const scheduleBlockSchema = new Schema(
  {
    day: { type: String, enum: DAYS, required: true },
    start: { type: String, match: /^\d{2}:\d{2}$/, required: true },
    end: { type: String, match: /^\d{2}:\d{2}$/, required: true },
    buildingId: { type: String, required: true },
    label: { type: String, maxlength: 40 },
  },
  { _id: false },
);

const userSchema = new Schema(
  {
    /**
     * Private, random id generated by the browser and kept in localStorage.
     * Acts like a password for the profile: never send it to other users.
     */
    anonId: { type: String, required: true, unique: true, index: true },
    /** Safe-to-share id used in chat, whiteboards and matches. */
    publicId: { type: String, required: true, unique: true, default: () => randomBytes(8).toString('hex') },
    displayName: { type: String, maxlength: 32, trim: true },
    major: { type: String, maxlength: 60, trim: true },
    status: { type: String, enum: ['commuter', 'resident'] },
    schedule: { type: [scheduleBlockSchema], default: [] },
    lookingFor: { type: [{ type: String, enum: LOOKING_FOR }], default: [] },
    strongSubjects: { type: [{ type: String, maxlength: 40 }], default: [] },
    needHelpSubjects: { type: [{ type: String, maxlength: 40 }], default: [] },
    lastSeenAt: { type: Date, default: () => new Date() },
    /** Most recent IP this user connected from (for IP bans). Never shown to other users. */
    lastIp: { type: String },
    isAdmin: { type: Boolean, default: false },
  },
  { timestamps: true },
);

userSchema.index({ 'schedule.day': 1, 'schedule.buildingId': 1 });
userSchema.index({ displayName: 1 });

export type UserDoc = InferSchemaType<typeof userSchema>;
export const User = model('User', userSchema);

export function displayNameOf(user: { displayName?: string | null; publicId: string }): string {
  return user.displayName?.trim() || `Bronco #${user.publicId.slice(0, 4)}`;
}

export async function getOrCreateUser(anonId: string) {
  return User.findOneAndUpdate(
    { anonId },
    { $set: { lastSeenAt: new Date() }, $setOnInsert: { anonId } },
    { upsert: true, new: true, setDefaultsOnInsert: true },
  );
}
